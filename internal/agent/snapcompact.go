func buildSnapArchive(text string) (string, error) {
	lines := strings.Split(strings.ToUpper(strings.Map(func(r rune) rune {
		if r == '\n' || r == '\t' || unicode.IsPrint(r) {
			return r
		}
		return ' '
	}, text)), "\n")
	const width, height, maxLines, maxFrames = 720, 560, 64, 8
	var frames [][]byte
	for start := 0; start < len(lines) && len(frames) < maxFrames; start += maxLines {
		end := start + maxLines
		if end > len(lines) {
			end = len(lines)
		}
		img := image.NewGray(image.Rect(0, 0, width, height))
		for y := 0; y < height; y++ {
			for x := 0; x < width; x++ {
				img.SetGray(x, y, color.Gray{Y: 255})
			}
		}
		for row, line := range lines[start:end] {
			for col, r := range []rune(line) {
				if col >= 115 {
					break
				}
				g, ok := glyphs[r]
				if !ok {
					g = glyphs['?']
				}
				for gy := 0; gy < 7; gy++ {
					for gx := 0; gx < 5; gx++ {
						if g[gy]&(1<<(4-gx)) != 0 {
							img.SetGray(8+col*6+gx, 8+row*8+gy, color.Gray{Y: 0})
						}
					}
				}
			}
		}
		var b bytes.Buffer
		if err := png.Encode(&b, img); err != nil {
			return "", err
		}
		frames = append(frames, b.Bytes())
	}
	data, err := json.Marshal(snapArchive{Version: 1, Frames: frames, Fallback: text})
	return string(data), err
}

func snapArchiveImages(raw string) ([]*provider.Image, string, error) {
	var archive snapArchive
	if err := json.Unmarshal([]byte(raw), &archive); err != nil {
		return nil, "", err
	}
	images := make([]*provider.Image, 0, len(archive.Frames))
	for _, data := range archive.Frames {
		images = append(images, &provider.Image{MimeType: "image/png", Data: data})
	}
	return images, archive.Fallback, nil
}
